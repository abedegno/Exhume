"""RAM in the original's layout for the open-toolchain build: every RAM symbol the original has
at the original's address, the rest after them.

    python3 profiles/armcc5/tools/openbuild/ramlayout.py --syms MAP_OR_ELF [--ram 0x20000000]
                                                          OBJ... > ram.ld

Decompiled source reaches some data through a neighbour's address (a wide view of one variable
that covers the next, a table read past its end, `&a + n` for b), as the original compiler laid
it out. Another compiler orders and aligns RAM its own way, so those reads land elsewhere. The
generated script puts each variable where the original has it: with -fdata-sections each one
is a section of its own (.data.NAME or .bss.NAME, the name the original's symbols give it), and
both kinds go into one output section loaded from flash (zeros for .bss), so a variable one
compiler made initialised and the other zero-initialised still lands in place. GNU ld stops on
a variable that has grown into the next one ('cannot move location counter backwards').

Clang may align a global more than the original did (a packed struct, a char array); where the
original address is not a multiple of that, the object's section alignment is lowered to fit,
in place, with objcopy --set-section-alignment. Cortex-M3 and later read and write halfwords
and words at any address (not LDRD, LDM or STM: a fault in the emulator shows that).

A name defined in more than one object (two files' statics) is not placed: it is reported."""
import argparse, collections, os, re, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), 'emu'))
import images

# objdump -h: "  5 .bss.g_buf   00000040  00000000  00000000  00000034  2**2"
SECTION = re.compile(r'^\s*\d+\s+(\.(?:data|bss)\.(\S+))\s+([0-9a-f]+)\s+[0-9a-f]+\s+[0-9a-f]+\s+[0-9a-f]+\s+2\*\*(\d+)', re.M)


def place(objs, ram_syms, ram=(0x20000000, 0x10000), objdump='arm-none-eabi-objdump', objcopy='arm-none-eabi-objcopy'):
    """(linker script text, notes). Lowers over-alignment in the objects as a side effect."""
    lo, size = ram
    found = collections.defaultdict(list)      # name -> [(obj, section, align)]
    for obj in objs:
        out = subprocess.run([objdump, '-h', obj], capture_output=True, text=True, check=True).stdout
        for sec, name, sz, align in SECTION.findall(out):
            if name in ram_syms: found[name].append((obj, sec, int(align)))
    notes, placed = [], []
    fixes = collections.defaultdict(list)
    for name, where in sorted(found.items()):
        if len(where) > 1:
            notes.append(f'{name}: defined in {len(where)} objects ({", ".join(os.path.basename(w[0]) for w in where)}), not placed')
            continue
        obj, sec, align = where[0]
        addr = ram_syms[name]
        if addr % (1 << align):
            fixes[obj] += ['--set-section-alignment', f'{sec}={min(addr & -addr, 8)}']
            notes.append(f'{name}: aligned to {1 << align}, lowered to {min(addr & -addr, 8)} for {addr:#010x}')
        placed.append((addr, name, sec))
    for obj, args in fixes.items():
        subprocess.run([objcopy] + args + [obj], check=True)
    lines = ['/* generated by profiles/armcc5/tools/openbuild/ramlayout.py: RAM in the original layout */',
             '.ram : {', '  _ram_start = .;']
    for addr, name, sec in sorted(placed):
        lines.append(f'  . = 0x{addr - lo:X}; KEEP(*({sec}))')
    lines += ['  *(.data .data.*)', '  *(.bss .bss.* COMMON)', '  . = ALIGN(4);', '  _ram_end = .;',
              '} > RAM AT > FLASH', '_ram_load = LOADADDR(.ram);']
    return '\n'.join(lines) + '\n', notes


def ram_symbols(path, ram):
    s = images.load_symbols(path)
    return {n: a for n, (a, z) in s.data.items() if ram[0] <= a < ram[0] + ram[1]}


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('objs', nargs='+'); ap.add_argument('--syms', required=True)
    ap.add_argument('--ram', default='0x20000000'); ap.add_argument('--ram-size', default='0x10000')
    o = ap.parse_args(argv)
    ram = (int(o.ram, 0), int(o.ram_size, 0))
    text, notes = place(o.objs, ram_symbols(o.syms, ram), ram)
    sys.stdout.write(text)
    for n in notes: print(n, file=sys.stderr)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
