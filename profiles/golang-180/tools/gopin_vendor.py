#!/usr/bin/env python3
"""Pin third-party Go vendor/upstream repositories to exact commits via .gopclntab lines.

Scores git commits in a cloned repository by matching Go function declaration line numbers
against `map/functions.tsv` (`.gopclntab` startlines) and optionally exports the winning
commit cleanly via `git archive`.

Usage:
    python3 gopin_vendor.py --funcs-tsv map/functions.tsv --repo /path/to/repo \
        --prefix github.com/foo/bar [--path-root src/vendor/] \
        [--before 2017-06-01] [--after 2015-01-01] [--subdir sub] [--export-dir DIR]
"""
import argparse
import csv
import os
import re
import shutil
import subprocess
import sys
from collections import defaultdict

FUNC_RE = re.compile(
    r'^\s*func\s+(?:\(\s*(?:[A-Za-z_]\w*\s+)?(\*?[A-Za-z_]\w*)\s*\)\s*)?([A-Za-z_]\w*)\s*\('
)


def load_targets(funcs_tsv, vendor_prefix, path_root='src/vendor/'):
    """Return {rel_file: [(func_key, startline), ...]} for functions under path_root + vendor_prefix."""
    prefix = f'{path_root.rstrip("/")}/{vendor_prefix.strip("/")}/'
    targets = defaultdict(list)
    with open(funcs_tsv) as f:
        for r in csv.DictReader(f, delimiter='\t'):
            fn = r['file']
            if not fn.startswith(prefix):
                continue
            rel = fn[len(prefix):]
            name = r['name']
            if '.init' in name or '.func' in name or '<autogenerated>' in fn:
                continue
            dot = name.rfind('/')
            tail = name[dot + 1:] if dot >= 0 else name
            parts = tail.split('.', 1)
            if len(parts) < 2:
                continue
            targets[rel].append((parts[1], int(r['startline'])))
    return targets


def parse_go_funcs(src_text):
    """Map func_key -> list of 1-based declaration line numbers in Go source."""
    found = defaultdict(list)
    for lineno, line in enumerate(src_text.splitlines(), 1):
        m = FUNC_RE.match(line)
        if not m:
            continue
        recv, fname = m.group(1), m.group(2)
        if fname == 'init':
            continue
        if recv:
            key = f'({recv}).{fname}' if recv.startswith('*') else f'{recv}.{fname}'
        else:
            key = fname
        found[key].append(lineno)
    return found


def score_commit(repo_dir, commit, targets, subdir=''):
    exact = near = total = checked_files = 0
    for rel, funcs in targets.items():
        git_path = f'{subdir}/{rel}' if subdir else rel
        p = subprocess.run(
            ['git', '-C', repo_dir, 'show', f'{commit}:{git_path}'],
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            text=True,
        )
        if p.returncode != 0:
            total += len(funcs)
            continue
        checked_files += 1
        found = parse_go_funcs(p.stdout)
        for key, target_line in funcs:
            total += 1
            lines = found.get(key)
            if not lines:
                continue
            best_diff = min(abs(l - target_line) for l in lines)
            if best_diff == 0:
                exact += 1
            elif best_diff <= 2:
                near += 1
    return exact, near, total, checked_files


def find_best_commit(funcs_tsv, repo_dir, vendor_prefix, path_root='src/vendor/',
                     before=None, after=None, subdir='', branch=None, top_n=10):
    targets = load_targets(funcs_tsv, vendor_prefix, path_root=path_root)
    if not targets:
        return None, []
    ranked_files = sorted(targets.items(), key=lambda kv: -len(kv[1]))[:4]
    screen_targets = dict(ranked_files)
    git_paths = [f'{subdir}/{rel}' if subdir else rel for rel in screen_targets]
    rev_args = [branch] if branch else ['--all']
    cmd = ['git', '-C', repo_dir, 'log', *rev_args, '--format=%H %ad %s', '--date=short']
    if before:
        cmd.append(f'--before={before}')
    if after:
        cmd.append(f'--after={after}')
    cmd.extend(['--', *git_paths])
    out = subprocess.check_output(cmd, text=True).splitlines()

    seen = set()
    candidates = []
    for line in out:
        parts = line.split(' ', 2)
        h = parts[0]
        if h in seen:
            continue
        seen.add(h)
        candidates.append((h, parts[1], parts[2] if len(parts) > 2 else ''))

    scored = []
    for h, dt, msg in candidates:
        ex, nr, tot, cf = score_commit(repo_dir, h, screen_targets, subdir)
        scored.append((ex, nr, -tot, dt, h, msg))
    scored.sort(reverse=True)

    full = []
    for _, _, _, dt, h, msg in scored[:top_n]:
        ex, nr, tot, cf = score_commit(repo_dir, h, targets, subdir)
        full.append((ex, nr, tot, cf, dt, h, msg))
    full.sort(key=lambda x: (x[0], x[1], x[3]), reverse=True)
    return (full[0] if full else None), full


def export_commit(repo_dir, commit, dst_dir, subdir=''):
    if os.path.exists(dst_dir):
        shutil.rmtree(dst_dir)
    os.makedirs(dst_dir, exist_ok=True)
    treeish = f'{commit}:{subdir}' if subdir else commit
    p1 = subprocess.Popen(['git', '-C', repo_dir, 'archive', treeish], stdout=subprocess.PIPE)
    p2 = subprocess.Popen(['tar', '-x', '-C', dst_dir], stdin=p1.stdout)
    p1.stdout.close()
    p2.wait()
    p1.wait()
    if p1.returncode != 0 or p2.returncode != 0:
        raise RuntimeError(f'git archive export failed for {treeish}')


def main(argv=None):
    ap = argparse.ArgumentParser(description='Pin a Go vendor/upstream repo commit via .gopclntab lines.')
    ap.add_argument('--funcs-tsv', default='map/functions.tsv')
    ap.add_argument('--repo', required=True, help='path to local git clone')
    ap.add_argument('--prefix', required=True, help='import prefix relative to path-root (e.g. github.com/foo/bar)')
    ap.add_argument('--path-root', default='src/vendor/', help='prefix in functions.tsv file column (default: src/vendor/)')
    ap.add_argument('--before', help='git --before date filter (e.g. 2017-06-01)')
    ap.add_argument('--after', help='git --after date filter (e.g. 2015-01-01)')
    ap.add_argument('--subdir', default='', help='subdirectory within repo matching prefix')
    ap.add_argument('--branch', help='optional git branch/rev instead of --all')
    ap.add_argument('--export-dir', help='export best commit cleanly into this directory')
    args = ap.parse_args(argv)

    best, full = find_best_commit(
        args.funcs_tsv, args.repo, args.prefix,
        path_root=args.path_root, before=args.before, after=args.after,
        subdir=args.subdir, branch=args.branch,
    )
    if not best:
        print(f'No matching commits found for {args.prefix}', file=sys.stderr)
        return 1
    for ex, nr, tot, cf, dt, h, msg in full[:5]:
        print(f'  {ex:3d}/{tot:<3d} exact (+{nr:2d} near, {cf} files) {dt} {h[:10]} {msg[:60]}')
    if args.export_dir:
        export_commit(args.repo, best[5], args.export_dir, subdir=args.subdir)
        print(f'Exported {best[5][:10]} -> {args.export_dir}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
