#!/usr/bin/env python3
"""gogatex.py: compare every first-party function of a candidate Go binary with a reference, and
keep a status file.

    gogatex.py REF CAND STATUS_TSV --prefix PREFIX [--exclude SUBSTR]...
                     [--name-prefix P]... [--src DIR] [--today DATE]
                     [--only REGEX] [--accept-regressions]

A function of REF is first-party when the file of its declaration starts with PREFIX and holds no
--exclude substring. A function is also selected when its name starts with a --name-prefix: a
closure created by an inlined library call has the library's file, and a compiler-generated
function (file <autogenerated>, such as a method wrapper) is selected this way too. Each is
compared with gocmpx.py; only MATCH counts as matched.

STATUS_TSV has a header line and one row per function:
    name  file  status  fitted  since
`fitted` is 1 when the function's source, from its first line to the first line of the next
function of the same file, holds the comment `// fitted:`; the source is read from DIR/file, and
without --src the column is 0. `since` is the ISO date on which the status last changed (DATE, or
today). Without --only, every selected function is scored and rows of functions no longer in REF
are dropped.

With --only REGEX, only the selected functions whose names match REGEX (re.search) are scored and
their rows replaced (one line `STATUS<TAB>name` is printed for each scored function, before the
summary lines; the full gate prints none); every other row of the existing file is kept as it is, and a row whose name
matches REGEX but which is no longer selected is dropped (a dropped row that was MATCH is a
regression, see below). The line `scored K functions` is printed before the last line. On a first
run, with no status file, --only produces a file that holds only the scored rows.

Prints `REGRESSED<TAB>name` for each row that was MATCH in the old file and is not now: a scored
function that no longer matches, and also a row that is absent from the new result for any reason
(gone from REF, no longer selected, dropped under --only). Rows that were not MATCH are dropped
silently. When a function was compared, it prints how the data operands of the functions scored
MATCH in this run were compared (see gocmpx.py): `data operands of the K functions scored MATCH:
C by content, T by type, F by function, M masked`. Then it prints the line `matched N of M; fitted F`, the totals of the whole file. When
anything regressed the exit status is 1 and the status file is not written, so the regression is
reported again on the next run; the totals are then those of the unchanged file and the line ends
with `(status file unchanged, not written)`. With --accept-regressions the file is written and
the exit status is 0. A selection that yields no function at all (usually a wrong --prefix) is a
tool error.

Tool errors exit with 2 and leave the status file as it was: a status file that does not parse
(a missing or wrong header, a row without five fields, text that is not UTF-8), a name with a tab
or newline in it, a binary that cannot be read, a bad REGEX, a comparator failure, an empty selection. A missing
status file is a first run. The file is written to a temporary file and moved into place.

Functions that share a name cannot be told apart in the status file, so each such name gets one
row with the status DUP, is not compared and is never matched; `duplicate names: K` is printed
before the last line when K > 0 (K counts scored names only).

When two selected functions start on the same line of a file, a fitted marker in that span is
counted for the first of them (in address order) only.
"""
import argparse
import collections
import datetime
import os
import re
import stat
import sys
import tempfile

import gobin
import gocmpx

MARKER = '// fitted:'
HEADER = ('name', 'file', 'status', 'fitted', 'since')


class ToolError(Exception):
    """Something wrong with the inputs or the tool, not a result of the comparison."""


def read_status(path):
    """{name: (name, file, status, fitted, since)} of an existing status file, in file order, {}
    when there is none; a file that does not parse raises ToolError."""
    try:
        with open(path, encoding='utf-8', newline='') as f:
            text = f.read()
    except FileNotFoundError:
        return {}
    except UnicodeDecodeError as e:
        raise ToolError('%s is not UTF-8: %s' % (path, e))
    lines = text.split('\n')
    if lines and lines[-1] == '':
        lines.pop()
    if not lines or tuple(lines[0].split('\t')) != HEADER:
        raise ToolError('%s: missing or wrong header line (want %s)' % (path, '\t'.join(HEADER)))
    old = {}
    for n, line in enumerate(lines[1:], 2):
        row = line.split('\t')
        if len(row) != 5:
            raise ToolError('%s:%d: %d fields, want 5' % (path, n, len(row)))
        old[row[0]] = tuple(row)
    return old


def selected(ref, prefix, excludes, name_prefixes=()):
    """The functions of ref, in address order, whose file is first-party, or whose name starts
    with one of name_prefixes (a closure made by an inlined library call has the library's file).
    Functions that share a name are all kept."""
    out = []
    for f in ref.funcs():
        by_file = f.file.startswith(prefix) and not any(x in f.file for x in excludes)
        if by_file or f.name.startswith(tuple(name_prefixes)):
            out.append(f)
    return out


def fitted_flags(ref, funcs, src):
    """[bool] for each of funcs: its source holds the fitted marker."""
    if not src:
        return [False] * len(funcs)
    starts, texts, flags, claimed = {}, {}, [], set()
    for f in ref.funcs():
        starts.setdefault(f.file, set()).add(f.start_line)
    for f in funcs:
        if f.file not in texts:
            try:
                with open(os.path.join(src, f.file), errors='replace') as fh:
                    texts[f.file] = fh.read().splitlines()
            except OSError:
                texts[f.file] = []
        later = [s for s in starts[f.file] if s > f.start_line]
        end = min(later) - 1 if later else len(texts[f.file])
        span = texts[f.file][max(f.start_line - 1, 0):end]
        first = (f.file, f.start_line) not in claimed
        claimed.add((f.file, f.start_line))
        flags.append(first and any(MARKER in line for line in span))
    return flags


def write_status(path, rows):
    """Write the rows to a temporary file beside path and move it into place."""
    fd, tmp = tempfile.mkstemp(prefix='.gogatex-', dir=os.path.dirname(os.path.abspath(path)))
    try:
        try:
            mode = stat.S_IMODE(os.stat(path).st_mode)
        except FileNotFoundError:
            umask = os.umask(0)
            os.umask(umask)
            mode = 0o666 & ~umask
        os.chmod(tmp, mode)
        with os.fdopen(fd, 'w', encoding='utf-8', newline='') as out:
            for row in (HEADER, *rows):
                out.write('\t'.join(row) + '\n')
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


Outcome = collections.namedtuple('Outcome', 'regressed dups matched total fitted scored written '
                                 'operands scored_rows', defaults=(None, ()))


def gate(ref, cand, status, prefix, excludes=(), name_prefixes=(), src=None, today=None,
         only=None, accept_regressions=False):
    """Compare and return an Outcome. The status file is written unless a scored function
    regressed and accept_regressions is false. only is a regex: when given, only the selected
    functions whose names match it are scored and the other rows of the file are kept."""
    today = today or datetime.date.today().isoformat()
    old = read_status(status)
    try:
        pattern = re.compile(only) if only is not None else None
    except re.error as e:
        raise ToolError('bad --only regex %r: %s' % (only, e))
    allfuncs = selected(ref, prefix, excludes, name_prefixes)
    for f in allfuncs:
        for what in (f.name, f.file):
            if any(c in what for c in '\t\r\n'):
                raise ToolError('function name or file with a tab or newline: %r' % what)
    if not allfuncs:
        raise ToolError('no function selected (prefix %r, %d excludes, %d name prefixes): '
                        'check --prefix; the status file is untouched'
                        % (prefix, len(excludes), len(name_prefixes)))
    funcs = [f for f in allfuncs if pattern is None or pattern.search(f.name)]
    flags = fitted_flags(ref, funcs, src)
    counts = {}
    for f in funcs:
        counts[f.name] = counts.get(f.name, 0) + 1
    # the comparator takes the first function of a name in the whole binary, so a name that
    # occurs twice anywhere in either binary cannot be compared
    everywhere = {}
    for binary in (ref, cand):
        seen = {}
        for f in binary.funcs():
            if f.name in counts:
                seen[f.name] = seen.get(f.name, 0) + 1
        for name, k in seen.items():
            everywhere[name] = max(everywhere.get(name, 0), k)
    counts = {name: max(k, everywhere.get(name, 0)) for name, k in counts.items()}
    unique = [f for f in funcs if counts[f.name] == 1]
    compared = gocmpx.compare_many(ref, cand, [f.name for f in unique]) if unique else []
    results = {r.name: r.status for r in compared}
    new, regressed = {}, []
    for f, fit in zip(funcs, flags):
        if f.name in new:
            continue
        st = results.get(f.name, 'DUP')
        was = old.get(f.name)
        since = was[4] if was and was[2] == st else today
        if was and was[2] == 'MATCH' and st != 'MATCH':
            regressed.append(f.name)
        new[f.name] = (f.name, f.file, st, '1' if fit else '0', since)
    if pattern is None:
        rows = list(new.values())
    else:
        # selected functions in address order, each with its new row or its kept old row; then
        # the old rows of functions no longer selected, unless the regex covers them
        rows, done = [], set()
        for f in allfuncs:
            if f.name in done:
                continue
            done.add(f.name)
            row = new.get(f.name) or old.get(f.name)
            if row:
                rows.append(row)
        rows += [r for name, r in old.items() if name not in done and not pattern.search(name)]
    # a row that was MATCH and is not in the result, for any reason, is a regression too
    kept = {r[0] for r in rows}
    regressed += [name for name, r in old.items() if r[2] == 'MATCH' and name not in kept]
    written = not regressed or accept_regressions
    if written:
        write_status(status, rows)
    shown = rows if written else list(old.values())     # the totals of the file as it stands
    return Outcome(regressed, sum(1 for c in counts.values() if c > 1),
                   sum(r[2] == 'MATCH' for r in shown), len(shown),
                   sum(r[3] == '1' for r in shown), len(new), written,
                   gocmpx.operand_totals(compared) if compared else None,
                   [(r[2], r[0]) for r in new.values()])


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('ref')
    ap.add_argument('cand')
    ap.add_argument('status')
    ap.add_argument('--prefix', required=True)
    ap.add_argument('--exclude', action='append', default=[])
    ap.add_argument('--name-prefix', action='append', default=[])
    ap.add_argument('--src')
    ap.add_argument('--today', default=None)
    ap.add_argument('--only', default=None, metavar='REGEX')
    ap.add_argument('--accept-regressions', action='store_true')
    args = ap.parse_args(argv[1:])
    try:
        ref, cand = gobin.load(args.ref), gobin.load(args.cand)
        out = gate(ref, cand, args.status, args.prefix, args.exclude, args.name_prefix, args.src,
                   args.today, args.only, args.accept_regressions)
    except Exception as e:
        print('gogatex: %s: %s' % (type(e).__name__, e) if not isinstance(e, ToolError)
              else 'gogatex: %s' % e, file=sys.stderr)
        return 2
    for name in out.regressed:
        print('REGRESSED\t' + name)
    if out.regressed and not out.written:
        print('status file not written: rerun with --accept-regressions to record the regressions')
    if args.only is not None:
        for st, name in out.scored_rows:
            print('%s\t%s' % (st, name))
    if out.operands:
        print('data operands of the %d functions scored MATCH: %s'
              % (out.operands[0], gocmpx.operand_text(out.operands[1])))
    if out.dups:
        print('duplicate names: %d' % out.dups)
    if args.only is not None:
        print('scored %d functions' % out.scored)
    print('matched %d of %d; fitted %d%s' % (out.matched, out.total, out.fitted,
          '' if out.written else ' (status file unchanged, not written)'))
    return 1 if out.regressed and not out.written else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
