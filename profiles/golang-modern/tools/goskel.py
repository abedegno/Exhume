#!/usr/bin/env python3
"""goskel.py: write a skeleton Go source tree that builds, from a Go binary.

    goskel.py BINARY OUT_DIR --prefix P/ [--modcache DIR] [--keep TAG] [--adopt-unmarked-stubs]

For every source file under P/ that the binary's line table names, writes OUT_DIR/<file without
P/>: the package clause, the imports its stubs need, and each function as a one-line stub,
`func Name(...) ... { panic("todo") } // skel:stub`, on the line at which the function starts in
the binary.
The named types of each package go into its types_recovered.go, with the layout the runtime type
information gives (see gotypes.py). The main package's types_recovered.go also imports every
other package of the tree, so that building the main package builds them all.

Signatures: a method's comes from its type's method table when the linker kept it. Otherwise
the parameters are guessed from the runtime's argument layout and pointer maps (so a pointer
and a length is written as a string, a type word and a pointer as any, a pointer, length and
capacity as []byte), and the results are those gosig.py recovers from the call sites and
return paths, one placeholder of a register's size per result register (int, or float64 for a
floating-point register), or none when it gives no answer: such stubs end in `signature
guessed`, and UNKNOWN.txt says `results from N call sites` or `results unknown`.
With no layout either, the stub has no parameters and ends in `signature unknown`. OUT_DIR/UNKNOWN.txt lists every guessed and
unknown signature, every declaration skipped and why, and every type written as a placeholder.

Not written: closures (.funcN), go and defer wrappers, method values (-fm), the package's own
init, and functions whose file is <autogenerated>, since the compiler makes these from the
source of the function that holds them. A generic function or type is written once, with as
many type parameters as its instances have, its signature or layout unknown.

Ownership is by marker. Only lines ending in a `// skel:stub` or `// skel:import` comment
belong to this tool. A file that exists is edited in place: its marker lines are replaced or
blanked, missing stubs and imports are written on free lines (blank lines outside any
declaration, comment or string), and every other byte stays as it was. A stub whose line is
taken goes to the next free line and is listed as moved. Functions and types declared by hand
anywhere in the package are not stubbed or recovered again. When a stub needs an import and no
free line is left above the stubs for it, the type is written as a placeholder instead.

types_recovered.go belongs to this tool and is rewritten; each declaration in it follows a
`// skel:type` line. If it holds a declaration without that line, nothing is written and the
run fails, naming the declaration, so that it can be moved to another file first.

--adopt-unmarked-stubs, for trees written before the markers: also treats one-line stubs of
the shape above without a marker as this tool's, files that hold nothing else (and their
imports) as wholly its own, and unmarked types_recovered.go and keep files carrying its
generated-file note as its own.

With --keep TAG, every package also gets zz_keep_<name>.go, built only with TAG: one variable
whose initialiser names every non-generic function and method of the package (as T.M or
(*T).M), stubs and hand-written ones alike, so that the linker keeps them although nothing calls
them; the main package's keep file also imports every package of the tree. A function in a file
with a //go:build line or a _GOOS/_GOARCH name is named from a keep file with the same
constraints. Keep files start with KEEP_NOTE; only such files are ever removed, and without
--keep those of an earlier run are.

Types of other packages are named only when the package can be imported: the standard library,
the tree's own packages, and, with --modcache, packages of the modules OUT_DIR/go.mod requires
that exist in that module cache. Any other type is written as a placeholder of its size and
alignment.
"""
