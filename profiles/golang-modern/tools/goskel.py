class Skeleton:
    def __init__(self, b, out, prefix, modcache=None, keep=None, adopt=False):
        self.b = b if not isinstance(b, str) else gobin.load(b)
        self.keep, self.adopt = keep, adopt
        self.types = gotypes.Types(self.b)
        self.out, self.prefix = out, prefix
        self.unknown = []           # (name, where, reason)
        self.counts = {}
        self._sig = None            # gosig's analysis of the binary, made when first needed
        self.pkgs = {}
        self._collect()
        self._add_type_only_packages()
        self.pkg_names = self.types.package_names()
        for p in self.pkgs.values():
            self.pkg_names.setdefault(p.path, 'main' if p.path == 'main' else
                                      re.sub(r'\W', '_', p.path.rsplit('/', 1)[-1]))
        self.importer = Importer(out, [p.path for p in self.pkgs.values() if p.path != 'main'],
                                 modcache)

    def note(self, name, where, reason, counted_as=None):
        """List a row in UNKNOWN.txt, counted under counted_as (default: the reason)."""
        self.unknown.append((name, where, reason))
        key = counted_as or reason
        self.counts[key] = self.counts.get(key, 0) + 1

    def _results(self, stub):
        """(result classes, call sites) recovered by gosig.py for a stub, or None."""
        if self._sig is None:
            try:
                self._sig = gosig.analysis(self.b, types=self.types)
            except (OSError, RuntimeError) as e:
                print('goskel.py: results not recovered: %s' % e, file=sys.stderr)
                self._sig = False
        if not self._sig:
            return None
        fi = self._sig.by_name.get(stub.func.name)
        r = self._sig.results(fi) if fi is not None else None
        return None if r is None else (r, self._sig.fs[fi].sites)

    def _collect(self):
        funcs = [f for f in self.b.funcs()
                 if f.file.startswith(self.prefix) and '/vendor/' not in f.file]
        dirs = {}                   # directory -> import path, from the names of its functions
        for f in funcs:
            pkgpath = package_of(f.name, f.file)
            if pkgpath and (pkgpath != 'main' or f.name == 'main.main'):
                dirs.setdefault(os.path.dirname(f.file[len(self.prefix):]), pkgpath)
        for f in funcs:
            rel = f.file[len(self.prefix):]
            pdir = os.path.dirname(rel)
            if pdir not in dirs:
                self.note(f.name, rel, 'skipped: no function names the package of the file')
                continue
            pkgpath = dirs[pdir]
            pkg = self.pkgs.setdefault(pkgpath, Package(pkgpath, pdir))
            stubs = pkg.files.setdefault(os.path.basename(rel), [])
            if not f.name.startswith(pkgpath + '.'):
                reason = 'not emitted: closure of code inlined into another package'
                self.counts[reason] = self.counts.get(reason, 0) + 1
                continue
            decl = parse_name(f.name[len(pkgpath) + 1:])
            if isinstance(decl, str):
                self.counts['not emitted: ' + decl] = self.counts.get(
                    'not emitted: ' + decl, 0) + 1
                continue
            stubs.append(Stub(f, decl))

    def _add_type_only_packages(self):
        """Packages of the tree that have named types but no functions in the line table, at
        the directory their import path gives."""
        roots = {p.path[:-len(p.dir)] for p in self.pkgs.values()
                 if p.dir and p.path != p.dir and p.path.endswith('/' + p.dir)}
        if len(roots) != 1:
            return
        root = roots.pop()
        for t in self.types.named_types():
            if t.pkgpath.startswith(root) and t.pkgpath not in self.pkgs:
                self.pkgs[t.pkgpath] = Package(t.pkgpath, t.pkgpath[len(root):])

    # Existing sources

    def _read_existing(self, pkg):
        d = os.path.join(self.out, pkg.dir)
        if not os.path.isdir(d):
            return
        for n in sorted(os.listdir(d)):
            if not n.endswith('.go') or n == TYPES_FILE or n.endswith('_test.go') or \
                    KEEP_FILE.match(n):
                continue
            with open(os.path.join(d, n), newline='') as f:
                src = parse_source(os.path.join(pkg.dir, n), f.read())
            if self.adopt and n in pkg.files and all(
                    dd[0] in ('package', 'import') or src.is_stub(dd, True) for dd in src.decls):
                continue                    # wholly an earlier run's: written afresh
            for i in range(len(src.lines)):
                if src.edited(i):
                    print('goskel.py: %s:%d: marker left on an edited function; kept as '
                          'hand-written' % (os.path.join(pkg.dir, n), i + 1), file=sys.stderr)
            pkg.sources[n] = src
            for decl in src.decls:
                kind, _, _, names, recv, _ = decl
                if src.is_stub(decl, self.adopt) or kind in ('package', 'import'):
                    continue
                if kind == 'func':
                    for name in names:
                        if name != 'init':
                            pkg.kept_funcs.add((recv, name))
                        if not recv:
                            pkg.taken.add(name)
                else:
                    pkg.taken.update(names)
                    if kind == 'type':
                        pkg.kept_types.update(names)

    def _check_types_file(self, pkg):
        """Refuse when types_recovered.go holds a declaration without the marker line."""
        path = os.path.join(self.out, pkg.dir, TYPES_FILE)
        if not os.path.exists(path):
            return
        with open(path, newline='') as f:
            text = f.read()
        if self.adopt and text.startswith(GENERATED_NOTE.split('\n')[0]) and \
                TYPE_MARK not in text:
            return                          # an earlier run's, from before the markers
        for decl in parse_source(os.path.join(pkg.dir, TYPES_FILE), text).decls:
            if decl[0] not in ('package', 'import') and \
                    not decl[5].startswith(TYPE_MARK + '\n'):
                raise Refused('%s:%d: %s %s has no "%s" line above it; this file is rewritten, '
                              'so move the declaration to another file of the package first' % (
                                  os.path.join(pkg.dir, TYPES_FILE), decl[1], decl[0],
                                  ', '.join(decl[3]) or '?', TYPE_MARK))

    # Types of a package

    def _package_types(self, pkg, stubs):
        """{name: Type or None (placeholder)}, {name: type parameter count} of generic types."""
        groups = {}
        for t in self.types.named_types():
            if t.pkgpath == pkg.path:
                groups.setdefault(type_args(t.name)[0], []).append(t)
        funcs = {s.decl.name for s in stubs if s.decl.kind == 'func'}
        generic = {}
        for name, g in groups.items():
            n = max(type_args(t.name)[1] for t in g)
            if n:
                generic[name] = n
        for s in stubs:
            if s.decl.kind == 'method' and s.decl.tparams:
                generic[s.decl.recv] = s.decl.tparams
        chosen = {}
        for name, g in sorted(groups.items()):
            if name in generic or name in pkg.kept_types:
                continue
            where = '%s.%s' % (pkg.path, name)
            if name in funcs or name in pkg.taken:
                self.note(where, pkg.dir, 'type skipped: name of a function or other '
                          'declaration (a type declared in a function)')
                continue
            t = gotypes.pick(g)
            if t is None:
                self.note(where, pkg.dir, 'type skipped: %d types of this name (types '
                          'declared in functions)' % len(g))
                continue
            chosen[name] = t
        for s in stubs:
            r = s.decl.recv
            if s.decl.kind == 'method' and r not in chosen and r not in generic and \
                    r not in pkg.kept_types:
                chosen[r] = None
                self.note('%s.%s' % (pkg.path, r), pkg.dir,
                          'type layout unknown: declared as struct{} for its methods')
        for name in generic:
            if name in pkg.kept_types:
                continue
            self.note('%s.%s' % (pkg.path, name), pkg.dir,
                      'generic type: type parameters and layout unknown')
        return chosen, {n: c for n, c in generic.items() if n not in pkg.kept_types}

    # Rendering

    def _renderer(self, pkg, declared, own_types):
        importer = self.importer

        def usable(t):
            return importer.ok(t.pkgpath, pkg.path)

        def local(t):
            return t.name in pkg.kept_types or own_types.get(t.name) is t

        return gotypes.Renderer(pkg.path, self.pkg_names, local=local, usable=usable,
                                taken=declared)

    def _signature(self, stub, chosen, r):
        """(text after the name, note) of a stub."""
        d, f = stub.decl, stub.func
        stub.sites = None
        if d.kind == 'init' or (d.kind == 'func' and d.name == 'main' and r.pkg == 'main'):
            return '()', ''
        if d.tparams:
            return '()', 'unknown'
        if d.kind == 'method':
            t = chosen.get(d.recv)
            holder = (t.ptr_to_this if d.ptr else t) if t is not None else None
            m = next((m for m in holder.methods if m.name == d.name), None) if holder else None
            if m is not None and m.type is not None:
                return r.signature(m.type), ''
        layout = arg_layout(self.b, f)
        if layout is None or d.kind == 'method' and not layout:
            return '()' + self._result_text(stub), 'unknown'
        if d.kind == 'method':
            layout = layout[1:]
        ptrs = arg_pointers(self.b, f)
        return '(' + ', '.join(guess(x, ptrs) for x in layout) + ')' + \
            self._result_text(stub), 'guessed'

    def _result_text(self, stub):
        """' T' or ' (T, ...)' for the results gosig.py recovers, with a placeholder of a
        register's size for each register (int, or float64 for a floating-point one); '' when
        there are none or they are not known."""
        found = self._results(stub)
        if found is None:
            stub.sites = None
            return ''
        classes, stub.sites = found
        outs = [RESULT_PLACEHOLDER[c] for c in classes]
        if not outs:
            return ''
        return ' ' + outs[0] if len(outs) == 1 else ' (' + ', '.join(outs) + ')'

    def _stub_text(self, stub, chosen, generic, r):
        """(stub line, note) of a stub: note is '', 'guessed' or 'unknown'."""
        d = stub.decl
        tp = ''
        if d.tparams:
            tp = '[%s any]' % ', '.join('T%d' % (i + 1) for i in range(d.tparams))
        sig, note = self._signature(stub, chosen, r)
        if d.kind == 'method':
            recv = d.recv
            if d.recv in generic:
                recv += '[%s]' % ', '.join('T%d' % (i + 1) for i in range(generic[d.recv]))
            head = 'func (%s%s) %s' % ('*' if d.ptr else '', recv, d.name)
        else:
            head = 'func %s%s' % (d.name, tp)
        text = '%s%s { panic("todo") } %s' % (head, sig, STUB_MARK)
        if note:
            text += ' signature ' + note
        return text, note

    def _note_stub(self, stub, note):
        where = '%s:%d' % (stub.func.file[len(self.prefix):], stub.line)
        found = stub.sites is not None
        results = 'results from %d call sites' % stub.sites if found else 'results unknown'
        if note == 'unknown':
            self.note(stub.func.name, where, 'signature unknown' + (
                ': ' + results if found else ''), 'signature unknown' + (
                ': results from call sites' if found else ''))
        elif note == 'guessed':
            self.note(stub.func.name, where, 'signature guessed: parameters from the argument '
                      'layout, ' + results, 'signature guessed: parameters from the argument '
                      'layout, ' + ('results from call sites' if found else results))
        else:
            self.counts['signature recovered'] = self.counts.get('signature recovered', 0) + 1

    def write(self):
        order = sorted(self.pkgs.values(), key=lambda p: p.path)
        for pkg in order:                   # everything is checked before anything is written
            self._read_existing(pkg)
            self._check_types_file(pkg)
        files = 0
        for pkg in order:
            stubs = []
            seen = set()
            for name in sorted(pkg.files):
                keep = []
                for s in sorted(pkg.files[name], key=lambda s: (s.line, s.func.entry)):
                    key = s.decl.key if s.decl.kind != 'init' else ('', 'init', s.line)
                    if key in seen or (s.decl.kind != 'init' and s.decl.key in pkg.kept_funcs):
                        continue
                    seen.add(key)
                    keep.append(s)
                pkg.files[name] = keep
                stubs += keep
            chosen, generic = self._package_types(pkg, stubs)
            declared = set(chosen) | set(generic) | pkg.taken | \
                {s.decl.name for s in stubs if s.decl.kind == 'func'}
            own_types = {n: t for n, t in chosen.items() if t is not None}
            stale = {n for n, src in pkg.sources.items() if n not in pkg.files and
                     any(src.owned(i, self.adopt) for i in range(len(src.lines)))}
            for name in sorted(set(pkg.files) | stale):
                self._edit_file(pkg, name, pkg.files.get(name, []), chosen, generic, declared,
                                own_types)
                files += name in pkg.files
            self._write_types(pkg, chosen, generic, declared, own_types)
            self._write_keep(pkg, stubs, generic, declared)
        self._write_unknown()
        self.counts['files'] = files
        self.counts['packages'] = len(self.pkgs)
        return self.counts

    def _placeholders(self, r, where):
        for t in r.placeholders:
            self.note(t.pkgpath + '.' + t.name if t.named else t.str, where,
                      'type written as a placeholder of its size')

    def _write_types(self, pkg, chosen, generic, declared, own_types):
        r = self._renderer(pkg, declared, own_types)
        body = []
        kinds = {}
        for name in sorted(chosen):
            t = chosen[name]
            if t is None:
                body.append('type %s struct{}' % name)
                continue
            kinds[t.kind] = kinds.get(t.kind, 0) + 1
            body.append(r.decl(t))
        for name in sorted(generic):
            body.append('type %s[%s any] struct{}' % (
                name, ', '.join('T%d' % (i + 1) for i in range(generic[name]))))
        for k, n in kinds.items():
            label = {gotypes.STRUCT: 'struct', gotypes.INTERFACE: 'interface'}.get(k, 'other')
            self.counts['types recovered: ' + label] = \
                self.counts.get('types recovered: ' + label, 0) + n
        self._placeholders(r, pkg.dir + '/' + TYPES_FILE)
        imports = dict(r.imports)
        blank = []
        if pkg.path == 'main':
            blank = sorted(p.path for p in self.pkgs.values() if p.path != 'main')
        lines = [GENERATED_NOTE, 'package %s\n' % self.pkg_names[pkg.path]]
        specs = ['\t' + self._spec(p, n) for p, n in sorted(imports.items())] + \
                ['\t_ "%s"' % p for p in blank if p not in imports]
        if specs:
            lines.append('import (\n%s\n)\n' % '\n'.join(specs))
        lines += ['%s\n%s\n' % (TYPE_MARK, b) for b in body]
        self._put(os.path.join(self.out, pkg.dir, TYPES_FILE), '\n'.join(lines))

    @staticmethod
    def _put(path, text):
        """Write text to path unless it already holds exactly that."""
        if os.path.exists(path):
            with open(path, newline='') as f:
                if f.read() == text:
                    return
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w', newline='') as f:
            f.write(text)

    def _default_name(self, ipath):
        return self.pkg_names.get(ipath) or ipath.rsplit('/', 1)[-1]

    def _spec(self, ipath, alias):
        """An import spec, with the name only when the path does not end in it."""
        if alias == self._default_name(ipath) == ipath.rsplit('/', 1)[-1]:
            return '"%s"' % ipath
        return '%s "%s"' % (alias, ipath)

    def _render_stubs(self, pkg, stubs, chosen, generic, declared, own_types, existing,
                      new_imports):
        """(renderer, [(stub line, note)]) with the file's existing imports, and new ones
        only if new_imports."""
        r = self._renderer(pkg, declared | set(existing.values()), own_types)
        r.imports = dict(existing)
        if not new_imports:
            r.may_import = lambda path: path in existing
        return r, [self._stub_text(s, chosen, generic, r) for s in stubs]

    def _import_in_use(self, src, i):
        """Whether line i is an owned import that code other than the stubs uses."""
        m = re.match(r'^import (?:(\w+|\.|_) )?"([^"]*)" // skel:import$', src.lines[i])
        if not m or m.group(1) in ('_', '.'):
            return False
        name = m.group(1) or self._default_name(m.group(2))
        decls = {n for d in src.decls if d[0] == 'import' or src.is_stub(d, self.adopt)
                 for n in range(d[1] - 1, d[2])}
        rx = re.compile(r'(?<![\w.])' + re.escape(name) + r'\s*\.')
        return any(rx.search(code) for n, code in enumerate(src.code) if n not in decls)

    def _edit_file(self, pkg, name, stubs, chosen, generic, declared, own_types):
        """Edit (or write) one source file in place: only marker lines change, and stubs and
        imports go on free lines."""
        path = os.path.join(self.out, pkg.dir, name)
        src = pkg.sources.get(name)
        if src is None:
            lines, ends_nl, crlf, eol = ['package %s' % self.pkg_names[pkg.path]], True, [], '\n'
        else:
            raw = src.text.split('\n')
            ends_nl = raw[-1] == ''
            if ends_nl:
                raw.pop()
            crlf = [r.endswith('\r') for r in raw]    # each line keeps its own ending
            eol = '\r\n' if 2 * sum(crlf) > len(crlf) else '\n'
            lines = list(src.lines[:len(raw)])
        ours = set()                        # indexes of lines this run may blank or trim
        for i in range(len(lines)):
            if src is not None and src.owned(i, self.adopt):
                if self._import_in_use(src, i):
                    continue            # hand-written code needs it: it stays as written
                lines[i] = ''
                ours.add(i)
        cur = Source('\n'.join(lines))
        depths, size = cur.depths(), len(lines)
        header = max([d[2] for d in cur.decls if d[0] in ('package', 'import')] + [1])
        first_hand = min([d[1] for d in cur.decls if d[0] not in ('package', 'import')] +
                         [10 ** 9])
        continues = re.compile(r'([-+*/%&|^<>=,(\[{.!:]|&&|\|\|)\s*$')

        after_open = []                     # whether the code before each line continues
        last = False
        for code in cur.code:
            after_open.append(last)
            if code.strip():
                last = bool(continues.search(code))

        def free(i):
            """Whether a stub or import may go on line index i."""
            if i >= len(lines):
                return True
            if lines[i].strip():
                return False
            if i >= size:
                return True
            return i not in cur.inside and depths[i] == 0 and not after_open[i]

        existing = {p: a or self._default_name(p) for a, p in cur.imports() if a not in ('_', '.')}
        first_stub = min([s.line for s in stubs] + [10 ** 9])
        end = min(first_hand - 1, first_stub - 1, len(lines) + len(stubs) + 1)
        slots = [i for i in range(header, end) if free(i)]
        r, texts = self._render_stubs(pkg, stubs, chosen, generic, declared, own_types,
                                      existing, True)
        new = sorted((p, n) for p, n in r.imports.items() if p not in existing)
        if len(new) > len(slots):           # no room for the imports: placeholders instead
            r, texts = self._render_stubs(pkg, stubs, chosen, generic, declared, own_types,
                                          existing, False)
            new = []
        floor = header
        for (ipath, alias), i in zip(new, slots):
            while len(lines) <= i:
                ours.add(len(lines))
                lines.append('')
            lines[i] = 'import %s %s' % (self._spec(ipath, alias), IMPORT_MARK)
            floor = i + 1
        where = pkg.dir + '/' + name
        self._placeholders(r, where)
        for s, (text, note) in zip(stubs, texts):
            self._note_stub(s, note)
            n = max(s.line, floor + 1)
            while not free(n - 1):
                n += 1
            if n != s.line:
                self.note(s.func.name, '%s:%d' % (where, s.line),
                          'line moved to %d: its line is taken' % n)
            while len(lines) < n:
                ours.add(len(lines))
                lines.append('')
            lines[n - 1] = text
        while lines and not lines[-1] and len(lines) - 1 in ours:
            lines.pop()
        ending = [('\r\n' if crlf[i] else '\n') if i < len(crlf) else eol
                  for i in range(len(lines))]
        if not ends_nl and lines:
            ending[-1] = ''
        self._put(path, ''.join(l + e for l, e in zip(lines, ending)))

    def _keep_refs(self, pkg, stubs, generic):
        """{(build expression, file name suffix): [expression]} naming every non-generic
        function and method of the package, stubs and hand-written ones alike, grouped by the
        constraints of the file that declares them; generic ones are listed in UNKNOWN.txt."""
        funcs = []
        for s in stubs:
            fname = os.path.basename(s.func.file)
            src = pkg.sources.get(fname)
            funcs.append((s.decl.recv, s.decl.ptr, s.decl.name,
                          bool(s.decl.tparams) or s.decl.recv in generic, s.func.name,
                          (src.constraint() if src else '', name_constraint(fname))))
        for fname, src in sorted(pkg.sources.items()):
            group = (src.constraint(), name_constraint(fname))
            for decl in src.decls:
                info = Source.func_info(decl) if decl[0] == 'func' and \
                    not src.is_stub(decl, self.adopt) else None
                if info:
                    recv, ptr, name, gen = info
                    funcs.append((recv, ptr, name, gen, '%s.%s%s' % (
                        pkg.path, '(*%s).' % recv if ptr else recv + '.' if recv else '',
                        name), group))
        groups, seen = {}, set()
        for recv, ptr, name, gen, full, group in funcs:
            if name == 'init' and not recv or name == 'main' and not recv and \
                    pkg.path == 'main' or name == '_':
                continue
            if gen:
                self.note(full, pkg.dir, 'not kept: generic')
                continue
            ref = ('(*%s).%s' % (recv, name) if ptr else '%s.%s' % (recv, name)) if recv \
                else name
            if ref not in seen:
                seen.add(ref)
                groups.setdefault(group, []).append(ref)
        return groups

    def _ours_keep(self, path):
        with open(path, newline='') as f:
            text = f.read()
        return text.startswith(KEEP_NOTE + '\n') or self.adopt and OLD_KEEP_NOTE in text

    def _write_keep(self, pkg, stubs, generic, declared):
        d = os.path.join(self.out, pkg.dir)
        base = 'zz_keep_%s' % self.pkg_names[pkg.path]
        files = {}
        if self.keep:
            groups = self._keep_refs(pkg, stubs, generic)
            groups.setdefault(('', ''), [])
            for k, ((expr, suffix), refs) in enumerate(sorted(groups.items())):
                name = '%s%s%s.go' % (base, '_c%d' % k if expr else '', suffix)
                var = 'keepAll' + ('_%d' % k if k else '')
                while var in declared:
                    var += '_'
                tag = self.keep if not expr else '%s && (%s)' % (self.keep, expr)
                lines = [KEEP_NOTE, '', '//go:build ' + tag, '',
                         '// It makes the linker keep every function of the package; the real',
                         '// program is built without the %s tag.' % self.keep, '',
                         'package %s' % self.pkg_names[pkg.path], '']
                if pkg.path == 'main' and not expr and not suffix:
                    others = sorted(p.path for p in self.pkgs.values() if p.path != 'main')
                    if others:
                        lines += ['import ('] + ['\t_ "%s"' % p for p in others] + [')', '']
                if refs:
                    # append makes the initialisation dynamic: a static slice that nothing
                    # reads would be dropped by the linker with everything it names.
                    lines.append('var %s = append([]any(nil),' % var)
                    lines += ['\t%s,' % r for r in refs]
                    lines.append(')')
                self.counts['kept by reference'] = self.counts.get('kept by reference', 0) + \
                    len(refs)
                files[name] = '\n'.join(lines) + '\n'
        if os.path.isdir(d):
            for n in os.listdir(d):
                if KEEP_FILE.match(n) and n not in files and self._ours_keep(os.path.join(d, n)):
                    os.remove(os.path.join(d, n))
        for name, text in files.items():
            path = os.path.join(d, name)
            if os.path.exists(path) and not self._ours_keep(path):
                raise Refused('%s: a hand-written file has the name of a keep file' % path)
            self._put(path, text)

    def _write_unknown(self):
        rows = sorted(self.unknown, key=lambda r: (r[2], r[0], r[1]))
        self._put(os.path.join(self.out, 'UNKNOWN.txt'), '# name\twhere\treason\n' +
                  ''.join('\t'.join(row) + '\n' for row in rows))


def write(b, out, prefix, modcache=None, keep=None, adopt=False):
    """Write the skeleton of binary b (a path or a gobin.Binary) into out; return counts.
    With keep, a build tag, also write the keep files that the tag enables; with adopt, take
    over unmarked stubs of an earlier run. Raises Refused, having written nothing, when
    types_recovered.go holds hand-written declarations."""
    return Skeleton(b, out, prefix, modcache, keep, adopt).write()


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('binary')
    ap.add_argument('out')
    ap.add_argument('--prefix', required=True, help='source file prefix of the tree, as P/')
    ap.add_argument('--modcache', help='module cache in which to look for imported packages')
    ap.add_argument('--keep', metavar='TAG', help='write keep files built only with this tag')
    ap.add_argument('--adopt-unmarked-stubs', action='store_true',
                    help='treat unmarked stubs of an earlier run as this tool\'s (one-time)')
    a = ap.parse_args(argv[1:])
    try:
        counts = write(a.binary, a.out, a.prefix, a.modcache, a.keep, a.adopt_unmarked_stubs)
    except Refused as e:
        sys.exit('goskel.py: nothing written: %s' % e)
    for k in sorted(counts):
        print('%s\t%d' % (k, counts[k]))


if __name__ == '__main__':
    main(sys.argv)
