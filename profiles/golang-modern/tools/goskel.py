# Function names

def split_top(s, sep='.'):
    """s split at each sep outside brackets, parentheses and braces."""
    parts, depth, cur = [], 0, []
    for c in s:
        if c in '([{':
            depth += 1
        elif c in ')]}':
            depth -= 1
        if c == sep and depth == 0:
            parts.append(''.join(cur))
            cur = []
        else:
            cur.append(c)
    parts.append(''.join(cur))
    return parts


def type_args(s):
    """('Name', number of type arguments) of 'Name[a,b]', or ('Name', 0)."""
    if '[' not in s:
        return s, 0
    i = s.index('[')
    return s[:i], len(split_top(s[i + 1:s.rindex(']')], ','))


class Decl:
    """What a function name declares. kind is 'func', 'method' or 'init'; recv is the receiver
    type's name, ptr whether the receiver is a pointer; tparams counts the type parameters of a
    generic function or of a method's generic receiver."""
    __slots__ = ('kind', 'name', 'recv', 'ptr', 'tparams')

    def __init__(self, kind, name, recv='', ptr=False, tparams=0):
        self.kind, self.name, self.recv, self.ptr, self.tparams = kind, name, recv, ptr, tparams

    @property
    def key(self):
        return (self.recv, self.name)


def parse_name(rest):
    """A Decl for the part of a function name after 'pkgpath.', or a string saying why the
    function is not declared in source."""
    if rest.endswith('-fm'):
        return 'method value wrapper'
    parts = split_top(rest)
    if rest == 'init':
        return 'package initialisation'
    if len(parts) == 2 and parts[0] == 'init' and parts[1].isdigit():
        return Decl('init', 'init')
    if parts[0].startswith('('):
        if len(parts) != 2:
            return 'closure or wrapper'
        recv = parts[0][1:-1]
        ptr = recv.startswith('*')
        recv, n = type_args(recv.lstrip('*'))
        return Decl('method', parts[1], recv, ptr, n)
    if len(parts) == 1:
        name, n = type_args(parts[0])
        return Decl('func', name, tparams=n)
    if len(parts) == 2 and not DERIVED.match(parts[1]) and parts[0]:
        recv, n = type_args(parts[0])
        return Decl('method', parts[1], recv, False, n)
    return 'closure or wrapper'


def package_of(name, path):
    """The import path in the function name, given its source file's path: the longest tail
    of the file's directory that the name starts with, or main, or None."""
    parts = path.split('/')[:-1]
    for i in range(len(parts)):
        cand = '/'.join(parts[i:])
        if name.startswith(cand + '.'):
            return cand
    if name.startswith('main.'):
        return 'main'
    return None


# Argument layouts

def arg_layout(b, f):
    """The runtime's argument description of a function as a list of items, each an
    (offset, size) pair or a list of items for a group; [] for no parameters; None when the
    description is cut short."""
    _, _, _, npcdata, _, _, nfuncdata = b._func_fields(f._off)
    if nfuncdata <= FUNCDATA_ARGINFO:
        return []
    off, = struct.unpack_from('<I', b.d, f._off + gobin.FUNC_HEADER + 4 * npcdata +
                              4 * FUNCDATA_ARGINFO)
    if off == 0xFFFFFFFF:
        return []
    p = b._off(b._md_word(gobin.MD_GOFUNC) + off)
    d = b.d
    stack = [[]]
    while True:
        o = d[p]
        p += 1
        if o == 0xFF:
            break
        if o == 0xFE:
            stack.append([])
        elif o == 0xFD:
            group = stack.pop()
            stack[-1].append(group)
        elif o >= 0xF0:                 # ... or an offset too large: the list is incomplete
            return None
        else:
            stack[-1].append((o, d[p]))
            p += 1
    return stack[0] if len(stack) == 1 else None


def arg_pointers(b, f):
    """The offsets of the argument words that hold pointers at any safe point, from the
    function's argument pointer maps."""
    _, _, _, npcdata, _, _, nfuncdata = b._func_fields(f._off)
    if nfuncdata < 1:
        return set()
    off, = struct.unpack_from('<I', b.d, f._off + gobin.FUNC_HEADER + 4 * npcdata)
    if off == 0xFFFFFFFF:
        return set()
    p = b._off(b._md_word(gobin.MD_GOFUNC) + off)
    n, nbit = struct.unpack_from('<ii', b.d, p)
    size = (nbit + 7) // 8
    out = set()
    for i in range(n):
        bits = b.d[p + 8 + i * size:p + 8 + (i + 1) * size]
        out.update(8 * k for k in range(nbit) if bits[k // 8] >> (k % 8) & 1)
    return out


SCALAR = {1: 'byte', 2: 'int16', 4: 'int32', 8: 'int'}
RESULT_PLACEHOLDER = {'int': SCALAR[8], 'float': 'float64'}     # one register each


def guess(item, ptrs):
    """A Go type of the shape of one item of an argument layout, given the offsets of the words
    that hold pointers: a pointer word is *byte, a group of a pointer and a length a string, of
    a type word and a pointer an interface (any), and of a pointer, length and capacity a
    []byte."""
    if isinstance(item, tuple):
        if item[1] == 8 and item[0] in ptrs:
            return '*byte'
        return SCALAR.get(item[1], '[%d]byte' % item[1])
    words = [x for x in item if isinstance(x, tuple) and x[1] == 8]
    if len(words) == len(item) and len(item) in (2, 3):
        shape = tuple(x[0] in ptrs for x in item)
        named = {(True, False): 'string', (False, True): 'any',
                 (True, False, False): '[]byte'}.get(shape)
        if named:
            return named
    return 'struct { %s }' % '; '.join('_ ' + guess(x, ptrs) for x in item)


# Source files that exist

class Source:
    """The top-level declarations of a Go file: (kind, first line, last line, names, recv,
    text) with lines counted from 1, the first line including the doc comment."""

    KEYWORD = re.compile(r'^(package|import|func|type|var|const)\b')
    FUNC = re.compile(r'^func\s*(?:\(\s*(?:\w+\s+)?\*?\s*(\w+)\s*(?:\[[^\]]*\])?\s*\))?\s*(\w+)')

    def __init__(self, text):
        self.text = text            # as read; the rest is with CRLF read as LF
        text = text.replace('\r\n', '\n')
        self.lines = text.split('\n')
        self.inside = set()         # lines that start inside a block comment or raw string
        self.code = self._strip(text).split('\n')
        self.depth = self.depths()
        self.decls = self._decls()

    def _top(self, i, marker):
        """Whether line i is at top level and its marker is a real comment, not text in a
        string or comment."""
        line = self.lines[i]
        at = line.rfind(marker)
        return i not in self.inside and self.depth[i] == 0 and at >= 0 and \
            not self.code[i][at:].strip()

    def owned(self, i, adopt=False):
        """Whether line i is this tool's: a marked stub or import exactly as written (or,
        adopting, an unmarked stub of its shape)."""
        line = self.lines[i]
        if OWNED_STUB.match(line) or OWNED_IMPORT.match(line):
            return self._top(i, '// skel:')
        return bool(adopt and UNMARKED_STUB.match(line) and i not in self.inside and
                    self.depth[i] == 0)

    def edited(self, i):
        """Whether line i carries a marker at top level but is no longer as written."""
        return bool(MARKED.match(self.lines[i])) and self._top(i, '// skel:') and \
            not self.owned(i)

    def is_stub(self, decl, adopt=False):
        """Whether a declaration is a stub this tool owns."""
        rows = [n for n in range(decl[1] - 1, decl[2])
                if not self.lines[n].lstrip().startswith('//')]
        return decl[0] == 'func' and len(rows) == 1 and self.owned(rows[0], adopt)

    def _strip(self, text):
        """text with comments and the contents of strings and runes blanked, keeping every
        line where it was."""
        out, i, n = [], 0, len(text)
        while i < n:
            c = text[i]
            if text.startswith('//', i):
                j = text.find('\n', i)
                j = n if j < 0 else j
                out.append(' ' * (j - i))
                i = j
            elif text.startswith('/*', i):
                j = text.find('*/', i + 2)
                j = n if j < 0 else j + 2
                self._mark_inside(text, i, j)
                out.append(re.sub(r'[^\n]', ' ', text[i:j]))
                i = j
            elif c in '"\'':
                j = i + 1
                while j < n and text[j] != c and text[j] != '\n':
                    if text.startswith('\\\n', j):
                        raise ValueError('line %d: backslash-newline inside a quoted string '
                                         '(not valid Go)' % (text.count('\n', 0, j) + 1))
                    j += 2 if text[j] == '\\' else 1
                j = min(j + 1, n)
                out.append(c + ' ' * (j - i - 2) + c)
                i = j
            elif c == '`':
                j = text.find('`', i + 1)
                j = n if j < 0 else j + 1
                self._mark_inside(text, i, j)
                out.append('`' + re.sub(r'[^\n]', ' ', text[i + 1:j - 1]) + '`')
                i = j
            else:
                out.append(c)
                i += 1
        return ''.join(out)

    def _mark_inside(self, text, i, j):
        pos, line = getattr(self, '_counted', (0, 0))     # newlines are counted once
        line += text.count('\n', pos, i)
        self.inside.update(range(line + 1, line + 1 + text.count('\n', i, j)))
        self._counted = (i, line)

    def depths(self):
        """The bracket depth at the start of each line."""
        out, depth = [], 0
        for line in self.code:
            out.append(depth)
            depth += sum(line.count(c) for c in '([{') - sum(line.count(c) for c in ')]}')
        return out

    def constraint(self):
        """The expression of the file's //go:build line, or ''."""
        for line in self.lines:
            if line.startswith('//go:build '):
                return line[len('//go:build '):].strip()
            if line.startswith('package '):
                break
        return ''

    def _decls(self):
        depth, starts = 0, []
        for n, line in enumerate(self.code):
            if depth == 0 and self.KEYWORD.match(line):
                starts.append(n)
            depth += sum(line.count(c) for c in '([{') - sum(line.count(c) for c in ')]}')
        decls = []
        for k, s in enumerate(starts):
            end = (starts[k + 1] if k + 1 < len(starts) else len(self.lines)) - 1
            # trailing lines with no code (blank, or only comments, // or /* */) are not part
            # of the declaration
            while end > s and not self.code[end].strip():
                end -= 1
            first = s
            while first > 0 and self.lines[first - 1].lstrip().startswith('//') and \
                    (k == 0 or first - 1 > decls[-1][2]):
                first -= 1
            kind = self.KEYWORD.match(self.code[s]).group(1)
            names, recv = self._names(kind, s, end)
            decls.append((kind, first + 1, end + 1, names, recv,
                          '\n'.join(self.lines[first:end + 1])))
        return decls

    def _names(self, kind, s, end):
        head = self.code[s]
        if kind == 'func':
            m = self.FUNC.match(head)
            return ([m.group(2)], m.group(1) or '') if m else ([], '')
        if kind in ('type', 'var', 'const'):
            rest = head[len(kind):].strip()
            if not rest.startswith('('):
                return re.findall(r'\w+', rest.split('=')[0].split(' ')[0] if kind == 'type'
                                  else rest.split('=')[0])[:1 if kind == 'type' else None], ''
            names = []
            for line in self.code[s + 1:end]:
                m = re.match(r'^\s(\w+(?:\s*,\s*\w+)*)', line)
                if m and not line.startswith('\t\t'):
                    names += re.findall(r'\w+', m.group(1)) if kind != 'type' else \
                        [m.group(1).split(',')[0].strip()]
            return names, ''
        return [], ''

    @staticmethod
    def func_info(decl):
        """(receiver type, pointer receiver, name, generic) of a func declaration, or None."""
        head = next((l for l in decl[5].split('\n') if not l.lstrip().startswith('//')), '')
        m = re.match(r'^func\s*(?:\(\s*(?:\w+\s+)?(\*?)\s*(\w+)\s*(\[[^\]]*\])?\s*\))?'
                     r'\s*(\w+)\s*(\[)?', head)
        if not m:
            return None
        return m.group(2) or '', bool(m.group(1)), m.group(4), bool(m.group(3) or m.group(5))

    def imports(self):
        """[(name or None, path)] of the import declarations."""
        out = []
        for kind, first, last, _, _, _ in self.decls:
            if kind != 'import':
                continue
            for n in range(first - 1, last):
                for m in re.finditer(r'(?:^|[\s(;])(\w+|\.|_)?\s*"([^"]+)"', self.lines[n]):
                    out.append((m.group(1), m.group(2)))
        return out

    def uses(self, name, first, last):
        """Whether name. is written in the code of lines first..last."""
        rx = re.compile(r'(?<![\w.])' + re.escape(name) + r'\s*\.')
        return any(rx.search(self.code[n]) for n in range(first - 1, last))


def parse_source(where, text):
    """Source(text), or Refused naming the file where when the text cannot be scanned."""
    try:
        return Source(text)
    except ValueError as e:
        raise Refused('%s: %s' % (where, e))


def name_constraint(filename):
    """The _GOOS, _GOARCH or _GOOS_GOARCH suffix of a file name that constrains it, or ''."""
    parts = filename[:-3].split('_')
    if len(parts) >= 3 and parts[-2] in GOOS and parts[-1] in GOARCH:
        return '_%s_%s' % (parts[-2], parts[-1])
    if len(parts) >= 2 and (parts[-1] in GOOS or parts[-1] in GOARCH):
        return '_' + parts[-1]
    return ''


# Import paths that can be used

class Importer:
    """Whether a package can be imported from the tree: the standard library, the tree's own
    packages, and packages of required modules found in the module cache."""

    def __init__(self, out, own, modcache):
        self.out, self.own, self.modcache = out, set(own), modcache
        self.module, self.requires, self.replaces = '', {}, {}
        gomod = os.path.join(out, 'go.mod')
        if os.path.exists(gomod):
            self._read_gomod(gomod)
        self.goroot = os.environ.get('GOROOT') or self._goroot()
        self._cache = {}

    @staticmethod
    def _goroot():
        import subprocess
        try:
            return subprocess.run(['go', 'env', 'GOROOT'], capture_output=True, text=True,
                                  check=True).stdout.strip()
        except (OSError, subprocess.CalledProcessError):
            return ''

    def _read_gomod(self, path):
        block = None
        with open(path) as f:
            for line in f:
                line = line.split('//')[0].strip()
                if not line:
                    continue
                if line.endswith('(') and len(line.split()) == 2:
                    block = line.split()[0]
                    continue
                if line == ')':
                    block = None
                    continue
                words = line.split()
                kw = block
                if not block:
                    kw, words = words[0], words[1:]
                if kw == 'module' and words:
                    self.module = words[0].strip('"')
                elif kw == 'require' and len(words) >= 2:
                    self.requires[words[0]] = words[1]
                elif kw == 'replace' and '=>' in words:
                    i = words.index('=>')
                    self.replaces[words[0]] = words[i + 1:]

    @staticmethod
    def _escape(path):
        return re.sub(r'[A-Z]', lambda m: '!' + m.group(0).lower(), path)

    def _module_dir(self, mod):
        if mod in self.replaces:
            target = self.replaces[mod]
            if target[0].startswith(('.', '/')):
                return os.path.join(self.out, target[0])
            if len(target) < 2:
                return None
            return os.path.join(self.modcache, '%s@%s' % (self._escape(target[0]), target[1]))
        return os.path.join(self.modcache, '%s@%s' % (self._escape(mod), self.requires[mod]))

    @staticmethod
    def _has_go(d):
        try:
            return any(n.endswith('.go') and not n.endswith('_test.go') for n in os.listdir(d))
        except OSError:
            return False

    def internal_ok(self, path, importer):
        parts = path.split('/')
        if 'internal' not in parts:
            return True
        root = '/'.join(parts[:len(parts) - 1 - parts[::-1].index('internal')])
        return importer == root or importer.startswith(root + '/')

    def ok(self, path, importer):
        if not self.internal_ok(path, importer) or path.startswith('vendor/') or path == 'main':
            return False
        if path in self.own:
            return True
        if path not in self._cache:
            self._cache[path] = self._exists(path)
        return self._cache[path]

    def _exists(self, path):
        first = path.split('/')[0]
        if '.' not in first:                        # the standard library
            if self.module and (path == self.module or path.startswith(self.module + '/')):
                return False                        # one of ours that is not in the tree
            return not self.goroot or self._has_go(os.path.join(self.goroot, 'src', path))
        if not self.modcache:
            return True
        mods = [m for m in self.requires if path == m or path.startswith(m + '/')]
        if not mods:
            return False
        mod = max(mods, key=len)
        d = self._module_dir(mod)
        if d and not os.path.isdir(d):
            return True                             # not downloaded yet: the build will say
        return bool(d) and self._has_go(os.path.join(d, path[len(mod) + 1:]))


